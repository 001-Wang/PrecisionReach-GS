function csvValue(value) {
    if (value == null) return "";
    const text = String(value);
    return /[",\n\r]/.test(text) ? `"${text.replaceAll('"', '""')}"` : text;
}

function mat4RowsFlat(m) {
    return Array.isArray(m) ? m.flat().map((v) => Number(v)) : new Array(16).fill("");
}

function poseFramesToCsv(frames) {
    const matrixCols = [];
    for (let r = 0; r < 4; r++) {
        for (let c = 0; c < 4; c++) matrixCols.push(`base_T_gripper_${r}${c}`);
    }
    const header = [
        "frame_index",
        "video_time_sec",
        "timestamp_ms",
        "wall_time",
        "viewer_role",
        "pose_source",
        "trajectory_mode",
        "ee_x",
        "ee_y",
        "ee_z",
        ...matrixCols,
    ];
    const rows = frames.map((frame) => {
        const pose = frame.ee_pose || {};
        const center = pose.gripper_center || [];
        const T = mat4RowsFlat(pose.base_T_gripper);
        return [
            frame.frame_index,
            frame.video_time_sec,
            frame.timestamp_ms,
            frame.wall_time,
            frame.viewer_role,
            frame.pose_source,
            frame.trajectory_mode,
            center[0],
            center[1],
            center[2],
            ...T,
        ].map(csvValue).join(",");
    });
    return [header.join(","), ...rows].join("\n");
}

