    function pushLine(arr, a, b, color) {
        arr.push(a[0], a[1], a[2], color[0], color[1], color[2]);
        arr.push(b[0], b[1], b[2], color[0], color[1], color[2]);
    }

    function pushCross(arr, p, radius, color) {
        pushLine(arr, [p[0] - radius, p[1], p[2]], [p[0] + radius, p[1], p[2]], color);
        pushLine(arr, [p[0], p[1] - radius, p[2]], [p[0], p[1] + radius, p[2]], color);
        pushLine(arr, [p[0], p[1], p[2] - radius], [p[0], p[1], p[2] + radius], color);
    }

    function pushThickLine(arr, a, b, color, radius = 0.025) {
        pushLine(arr, a, b, color);
        pushLine(arr, [a[0] + radius, a[1], a[2]], [b[0] + radius, b[1], b[2]], color);
        pushLine(arr, [a[0] - radius, a[1], a[2]], [b[0] - radius, b[1], b[2]], color);
        pushLine(arr, [a[0], a[1] + radius, a[2]], [b[0], b[1] + radius, b[2]], color);
        pushLine(arr, [a[0], a[1] - radius, a[2]], [b[0], b[1] - radius, b[2]], color);
    }

    function pushSquare(arr, center, size, color) {
        const z = center[2];
        const p1 = [center[0] - size, center[1] - size, z];
        const p2 = [center[0] + size, center[1] - size, z];
        const p3 = [center[0] + size, center[1] + size, z];
        const p4 = [center[0] - size, center[1] + size, z];
        pushLine(arr, p1, p2, color);
        pushLine(arr, p2, p3, color);
        pushLine(arr, p3, p4, color);
        pushLine(arr, p4, p1, color);
    }

    function pushBoxFromFrame(arr, T, halfSize, color, toScene = robotPointToColmap) {
        const corners = [
            [-halfSize[0], -halfSize[1], -halfSize[2]], [halfSize[0], -halfSize[1], -halfSize[2]],
            [halfSize[0], halfSize[1], -halfSize[2]], [-halfSize[0], halfSize[1], -halfSize[2]],
            [-halfSize[0], -halfSize[1], halfSize[2]], [halfSize[0], -halfSize[1], halfSize[2]],
            [halfSize[0], halfSize[1], halfSize[2]], [-halfSize[0], halfSize[1], halfSize[2]],
        ].map((p) => toScene(transformPoint(T, p)));
        const edges = [[0, 1], [1, 2], [2, 3], [3, 0], [4, 5], [5, 6], [6, 7], [7, 4], [0, 4], [1, 5], [2, 6], [3, 7]];
        for (const [a, b] of edges) pushLine(arr, corners[a], corners[b], color);
    }

    function pushRingFromFrame(arr, T, radius, color, segments = 18, toScene = robotPointToColmap) {
        let prev = null;
        for (let i = 0; i <= segments; i++) {
            const a = (i / segments) * Math.PI * 2;
            const p = toScene(transformPoint(T, [Math.cos(a) * radius, Math.sin(a) * radius, 0]));
            if (prev) pushLine(arr, prev, p, color);
            prev = p;
        }
    }

    function pushSimpleGripper(arr, handT, color, toScene = robotPointToColmap) {
        const palm = mat4RowsMul(handT, mat4Translation(0, 0, 0.035));
        pushBoxFromFrame(arr, palm, [0.055, 0.055, 0.035], color, toScene);
        const leftBase = mat4RowsMul(handT, mat4Translation(0, 0.035, 0.105));
        const rightBase = mat4RowsMul(handT, mat4RowsMul(mat4RotZ(Math.PI), mat4Translation(0, 0.035, 0.105)));
        const fingerColor = [0.96, 0.96, 0.92];
        pushBoxFromFrame(arr, leftBase, [0.014, 0.012, 0.055], fingerColor, toScene);
        pushBoxFromFrame(arr, rightBase, [0.014, 0.012, 0.055], fingerColor, toScene);
        const tcp = toScene(transformPoint(handT, [0, 0, 0.15]));
        pushCross(arr, tcp, 0.035, [1.0, 0.25, 0.25]);
    }

    function transformPoint(T, p) {
        return [
            T[0][0] * p[0] + T[0][1] * p[1] + T[0][2] * p[2] + T[0][3],
            T[1][0] * p[0] + T[1][1] * p[1] + T[1][2] * p[2] + T[1][3],
            T[2][0] * p[0] + T[2][1] * p[1] + T[2][2] * p[2] + T[2][3],
        ];
    }

